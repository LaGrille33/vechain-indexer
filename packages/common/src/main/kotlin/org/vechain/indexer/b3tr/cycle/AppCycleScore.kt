package org.vechain.indexer.b3tr.cycle

import java.math.BigDecimal
import org.springframework.data.annotation.Id
import org.springframework.data.mongodb.core.mapping.Document
import org.springframework.data.mongodb.core.mapping.Field
import org.springframework.data.mongodb.core.mapping.FieldType
import org.vechain.indexer.IndexerNames
import org.vechain.indexer.utils.IdUtils.generateId

@Document(collection = IndexerNames.APP_CYCLE_SCORE.COLLECTION)
data class AppCycleScore(
    @Id val id: String,
    val appId: String,
    val roundId: Int,
    val name: String,
    val slug: String,
    val channelName: String?,
    val status: String,
    // Discord stats
    val discordMessageCount: Int,
    val discordParticipants: Int,
    val discordSentiment: String,
    val discordPosTokens: Int,
    val discordNegTokens: Int,
    // On-chain stats
    val onchainRank: Int?,
    val onchainRankDelta: Int?,
    @Field(targetType = FieldType.DECIMAL128) val onchainAllocB3tr: BigDecimal?,
    @Field(targetType = FieldType.DECIMAL128) val onchainDistributedB3tr: BigDecimal?,
    val onchainActions: Long?,
    val onchainWau: Long?,
    val onchainNewUsers: Long?,
    @Field(targetType = FieldType.DECIMAL128) val onchainActivityScore: BigDecimal?,
    @Field(targetType = FieldType.DECIMAL128) val onchainDistributionScore: BigDecimal?,
    // 5-dimension breakdown (each 0-20)
    val breakdownCommunityTeam: Int,
    val breakdownStrategic: Int,
    val breakdownHealth: Int,
    val breakdownActivity: Int,
    val breakdownDistribution: Int,
    val total: Int,
    val allocation: Int,
    val confidence: String?,
    val tier: String?,
    val updatedAt: Long,
) {
    constructor(
        appId: String,
        roundId: Int,
        name: String,
        slug: String,
        channelName: String?,
        status: String,
        discordMessageCount: Int,
        discordParticipants: Int,
        discordSentiment: String,
        discordPosTokens: Int,
        discordNegTokens: Int,
        onchainRank: Int?,
        onchainRankDelta: Int?,
        onchainAllocB3tr: BigDecimal?,
        onchainDistributedB3tr: BigDecimal?,
        onchainActions: Long?,
        onchainWau: Long?,
        onchainNewUsers: Long?,
        onchainActivityScore: BigDecimal?,
        onchainDistributionScore: BigDecimal?,
        breakdownCommunityTeam: Int,
        breakdownStrategic: Int,
        breakdownHealth: Int,
        breakdownActivity: Int,
        breakdownDistribution: Int,
        total: Int,
        allocation: Int,
        confidence: String?,
        tier: String?,
        updatedAt: Long,
    ) : this(
        id = generateId(appId, "$roundId"),
        appId = appId,
        roundId = roundId,
        name = name,
        slug = slug,
        channelName = channelName,
        status = status,
        discordMessageCount = discordMessageCount,
        discordParticipants = discordParticipants,
        discordSentiment = discordSentiment,
        discordPosTokens = discordPosTokens,
        discordNegTokens = discordNegTokens,
        onchainRank = onchainRank,
        onchainRankDelta = onchainRankDelta,
        onchainAllocB3tr = onchainAllocB3tr,
        onchainDistributedB3tr = onchainDistributedB3tr,
        onchainActions = onchainActions,
        onchainWau = onchainWau,
        onchainNewUsers = onchainNewUsers,
        onchainActivityScore = onchainActivityScore,
        onchainDistributionScore = onchainDistributionScore,
        breakdownCommunityTeam = breakdownCommunityTeam,
        breakdownStrategic = breakdownStrategic,
        breakdownHealth = breakdownHealth,
        breakdownActivity = breakdownActivity,
        breakdownDistribution = breakdownDistribution,
        total = total,
        allocation = allocation,
        confidence = confidence,
        tier = tier,
        updatedAt = updatedAt,
    )
}
