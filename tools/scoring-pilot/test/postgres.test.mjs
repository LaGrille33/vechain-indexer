import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { PGlite } from '@electric-sql/pglite';

let db;
let fixtures;
const version = 'activity-distribution-mongo-parity-v1';

before(async () => {
  db = new PGlite();
  for (const file of ['001-schema.sql', '002-calculation.sql']) {
    await db.exec(await readFile(new URL(`../sql/${file}`, import.meta.url), 'utf8'));
  }
  fixtures = JSON.parse(await readFile(new URL('../../../packages/indexer/build/reports/scoring-pilot/kotlin-reference.json', import.meta.url), 'utf8'));
});
after(async () => { await db?.close(); });

async function snapshot(inputs, { complete = true, expected = inputs.length } = {}) {
  const id = randomUUID();
  await db.query(`INSERT INTO reputation_pilot.round_snapshot
    (snapshot_id,network,round_id,source_block_number,source_block_id,round_end_timestamp,
     input_hash,expected_app_count,new_user_history_complete,source_manifest)
    VALUES ($1,'mainnet',122,100,$2,0,$3,$4,$5,'{}')`,
    [id, `0x${'a'.repeat(64)}`, id.replaceAll('-', '').repeat(2), expected, complete]);
  for (const input of inputs) {
    await db.query(`INSERT INTO reputation_pilot.app_round_metric
      VALUES ($1,$2,$3,$4,$5,$6,$7)`, [id, input.appId, input.activeUsers,
      input.newUsers, input.actions, input.allocated, input.distributed]);
  }
  return id;
}
async function run(snapshotId, formula = version) {
  const id = randomUUID();
  await db.query(`INSERT INTO reputation_pilot.scoring_run
    (run_id,snapshot_id,formula_version,code_revision) VALUES ($1,$2,$3,'fixture-v1')`, [id, snapshotId, formula]);
  return id;
}
const normal = value => {
  const text = String(value);
  return text.includes('.') ? text.replace(/0+$/, '').replace(/\.$/, '') : text;
};

test('Postgres results match every decimal and rank generated by the current Kotlin calculator', async () => {
  for (const fixture of fixtures) {
    const id = await snapshot(fixture.inputs);
    const { rows } = await db.query('SELECT * FROM reputation_pilot.calculate_snapshot($1)', [id]);
    assert.equal(rows.length, fixture.expected.length, fixture.name);
    for (let i = 0; i < rows.length; i++) {
      for (const [key, expected] of Object.entries(fixture.expected[i])) {
        assert.equal(normal(rows[i][key]), normal(expected), `${fixture.name}: ${rows[i].app_id} ${key}`);
      }
    }
  }
});

test('execution persists all rows once and retries do not recompute completed runs', async () => {
  const id = await snapshot(fixtures[2].inputs);
  const runId = await run(id);
  await db.query('SELECT reputation_pilot.execute_run($1)', [runId]);
  const first = await db.query('SELECT * FROM reputation_pilot.scoring_run WHERE run_id=$1', [runId]);
  await db.query('SELECT reputation_pilot.execute_run($1)', [runId]);
  const retry = await db.query('SELECT * FROM reputation_pilot.scoring_run WHERE run_id=$1', [runId]);
  assert.deepEqual(retry.rows, first.rows);
  const { rows } = await db.query('SELECT count(*)::int AS count FROM reputation_pilot.app_round_score WHERE run_id=$1', [runId]);
  assert.equal(rows[0].count, 3);
  assert.equal(first.rows[0].status, 'completed');
});

test('incomplete population and incomplete new-user history fail without storing partial results', async () => {
  for (const options of [{ expected: 4 }, { complete: false }]) {
    const id = await snapshot(fixtures[2].inputs, options);
    const runId = await run(id);
    await assert.rejects(db.query('SELECT reputation_pilot.execute_run($1)', [runId]), /incomplete_/);
    const { rows } = await db.query('SELECT status FROM reputation_pilot.scoring_run WHERE run_id=$1', [runId]);
    assert.equal(rows[0].status, 'pending');
    const saved = await db.query('SELECT count(*)::int AS count FROM reputation_pilot.app_round_score WHERE run_id=$1', [runId]);
    assert.equal(saved.rows[0].count, 0);
  }
  const input = { ...fixtures[2].inputs[1], newUsers: null };
  const id = await snapshot([input]);
  await assert.rejects(db.query('SELECT * FROM reputation_pilot.calculate_snapshot($1)', [id]), /incomplete_new_user_history/);
});

test('snapshots freeze at run registration and saved results cannot be overwritten', async () => {
  const id = await snapshot(fixtures[2].inputs);
  const runId = await run(id);
  await assert.rejects(db.query('UPDATE reputation_pilot.app_round_metric SET actions=999 WHERE snapshot_id=$1', [id]), /frozen/);
  await assert.rejects(db.query('DELETE FROM reputation_pilot.app_round_metric WHERE snapshot_id=$1', [id]), /frozen/);
  await db.query('SELECT reputation_pilot.execute_run($1)', [runId]);
  await assert.rejects(db.query('UPDATE reputation_pilot.app_round_score SET subtotal=0 WHERE run_id=$1', [runId]), /immutable/);
  await assert.rejects(db.query("UPDATE reputation_pilot.scoring_run SET status='pending' WHERE run_id=$1", [runId]), /immutable/);
  await assert.rejects(db.query("UPDATE reputation_pilot.scoring_run SET code_revision='other' WHERE run_id=$1", [runId]), /immutable/);
  await db.query("UPDATE reputation_pilot.scoring_run SET status='validated' WHERE run_id=$1", [runId]);
  await db.query("UPDATE reputation_pilot.scoring_run SET status='approved' WHERE run_id=$1", [runId]);
  await assert.rejects(db.query('DELETE FROM reputation_pilot.scoring_run WHERE run_id=$1', [runId]), /immutable/);
});

test('unsupported formula versions cannot populate results', async () => {
  const id = await snapshot(fixtures[2].inputs);
  const runId = await run(id, 'unknown');
  await assert.rejects(db.query('SELECT reputation_pilot.execute_run($1)', [runId]), /unsupported_formula/);
});

test('a run cannot be marked completed without its complete saved population', async () => {
  const id = await snapshot(fixtures[2].inputs);
  const runId = await run(id);
  await assert.rejects(db.query("UPDATE reputation_pilot.scoring_run SET status='completed' WHERE run_id=$1", [runId]), /incomplete_saved_results/);
});
